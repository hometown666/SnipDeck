import type { Driver, RunEvent, RunRequest } from '@snipdeck/core'
import { spawn } from 'node:child_process'
import { mkdirSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import iconv from 'iconv-lite'

const CONTROL_CHARS = /[&|()%^<>\n]/
const TMP_TTL_MS = 7 * 24 * 60 * 60 * 1000
const HEALTH_TTL_MS = 30_000

export function needsTempCmd(cmd: string): boolean {
  return CONTROL_CHARS.test(cmd)
}

export function decodeOutput(buf: Buffer): string {
  if (buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) {
    return buf.subarray(3).toString('utf8')
  }
  const s = buf.toString('utf8')
  if (!s.includes('\uFFFD')) return s
  return iconv.decode(buf, 'gbk')
}

function killTree(pid: number | undefined): void {
  if (!pid) return
  try {
    spawn('taskkill', ['/pid', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true })
  } catch {
    // ignore
  }
}

/**
 * 批处理里落单的 `%` 会被吞掉（`echo 100%` 打印 `100`），
 * 而命令行直传时是原样输出。为了两种路径行为一致，把不属于
 * `%var%` / `%1` / `%~dp0` / `%%` 的单个 `%` 转义成 `%%`。
 */
export function escapeForBatch(cmd: string): string {
  return cmd.replace(/%(?!%|\w+%|[\d*~])/g, '%%')
}

export type ExecDriverOptions = {
  bridgeRoot: string
  tmpDir: string
  defaultTimeout?: number
  tmpTtlMs?: number
}

export class ExecDriver implements Driver {
  readonly kind = 'exec'
  /** 队列尾巴：只有上一条命令真正结束（含失败/超时）才会释放 */
  private tail: Promise<void> = Promise.resolve()
  private queued = 0
  private healthAt = 0
  private healthOk = false
  private healthInFlight: Promise<boolean> | null = null

  constructor(private opts: ExecDriverOptions) {
    mkdirSync(opts.tmpDir, { recursive: true })
    this.sweepTmp()
  }

  get queueLength(): number {
    return this.queued
  }

  get lastHealthOkAt(): number {
    return this.healthOk ? this.healthAt : 0
  }

  run(req: RunRequest): AsyncIterable<RunEvent> {
    return req.queue ? this.serialized(req) : this.execOnce(req)
  }

  /**
   * 全局串行队列。command.txt 是单车道，且 ahk.bat 自身没有锁，
   * 两条并发调用会互相覆盖，所以走桥的命令必须在这里严格 FIFO。
   * 注意：必须把「跑完」而不是「开始跑」作为释放信号，否则队列形同虚设。
   */
  private async *serialized(req: RunRequest): AsyncGenerator<RunEvent> {
    const prev = this.tail
    let release!: () => void
    this.tail = new Promise<void>((r) => {
      release = r
    })
    const waitFrom = Date.now()
    this.queued++
    try {
      await prev
      const waitedMs = Date.now() - waitFrom
      if (waitedMs >= 50) {
        yield { type: 'queued', stepIndex: req.stepIndex, waitedMs }
      }
      yield* this.execOnce(req)
    } finally {
      this.queued--
      release()
    }
  }

  /** 带 TTL 与单飞（in-flight 去重）的健康检查：别让每个 /api/health 都写一次 command.txt */
  health(force = false): Promise<boolean> {
    if (!force && this.healthAt > 0 && Date.now() - this.healthAt < HEALTH_TTL_MS) {
      return Promise.resolve(this.healthOk)
    }
    if (this.healthInFlight) return this.healthInFlight
    const p = this.probeHealth().finally(() => {
      this.healthInFlight = null
    })
    this.healthInFlight = p
    return p
  }

  private async probeHealth(): Promise<boolean> {
    try {
      const bat = join(this.opts.bridgeRoot, 'ahk.bat')
      let ok = false
      for await (const ev of this.run({
        shell: 'cmd',
        cmd: `call "${bat}" status`,
        timeout: 15,
        queue: true,
        stepIndex: -1,
      })) {
        if (ev.type === 'exit') ok = ev.ok
      }
      this.healthOk = ok
      this.healthAt = Date.now()
      return ok
    } catch {
      this.healthOk = false
      this.healthAt = Date.now()
      return false
    }
  }

  private sweepTmp(): void {
    const ttl = this.opts.tmpTtlMs ?? TMP_TTL_MS
    const now = Date.now()
    try {
      for (const name of readdirSync(this.opts.tmpDir)) {
        if (!name.startsWith('run-')) continue
        const p = join(this.opts.tmpDir, name)
        try {
          if (now - statSync(p).mtimeMs > ttl) unlinkSync(p)
        } catch {
          // 单个文件删不掉不影响启动
        }
      }
    } catch {
      // 目录不可读就算了
    }
  }

  private async *execOnce(req: RunRequest): AsyncGenerator<RunEvent> {
    const t0 = Date.now()
    yield { type: 'start', stepIndex: req.stepIndex, cmd: req.cmd }

    let batFile: string | null = null
    let args: string[]
    let verbatim = false

    if (req.shell === 'powershell') {
      args = ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', req.cmd]
    } else if (needsTempCmd(req.cmd)) {
      batFile = join(
        this.opts.tmpDir,
        `run-${Date.now()}-${Math.random().toString(36).slice(2, 8)}.cmd`,
      )
      const header = '@echo off\r\nrem generated by snipdeck exec driver\r\nsetlocal EnableDelayedExpansion\r\n'
      writeFileSync(batFile, iconv.encode(header + escapeForBatch(req.cmd) + '\r\n', 'gbk'))
      // call + 引号路径：cmd /s 会剥掉 /c 后首尾引号，直接传路径遇空格会截断；
      // call 内置命令带引号参数可正确处理含空格路径
      args = ['/d', '/s', '/c', `call "${batFile}"`]
      verbatim = true
    } else {
      args = ['/d', '/s', '/c', `"${req.cmd}"`]
      verbatim = true
    }

    const command = req.shell === 'powershell' ? 'powershell.exe' : 'cmd.exe'
    // windowsHide：服务将来以计划任务（无控制台）运行时，避免每条命令闪一个黑框
    const child = spawn(command, args, { windowsVerbatimArguments: verbatim, windowsHide: true })

    const outChunks: Buffer[] = []
    const errChunks: Buffer[] = []
    child.stdout?.on('data', (c: Buffer) => outChunks.push(c))
    child.stderr?.on('data', (c: Buffer) => errChunks.push(c))

    let timedOut = false
    const timer = setTimeout(() => {
      timedOut = true
      killTree(child.pid)
    }, req.timeout * 1000)

    let code: number | null = null
    try {
      code = await new Promise<number | null>((resolve) => {
        child.on('close', (c) => resolve(c))
        child.on('error', () => resolve(null))
      })
    } finally {
      clearTimeout(timer)
    }

    const stdout = decodeOutput(Buffer.concat(outChunks))
    const stderr = decodeOutput(Buffer.concat(errChunks))
    if (stdout) yield { type: 'stdout', stepIndex: req.stepIndex, data: stdout }
    if (stderr) yield { type: 'stderr', stepIndex: req.stepIndex, data: stderr }

    yield {
      type: 'exit',
      stepIndex: req.stepIndex,
      ok: !timedOut && code === 0,
      exitCode: code ?? undefined,
      durationMs: Date.now() - t0,
      timedOut,
    }
  }
}
